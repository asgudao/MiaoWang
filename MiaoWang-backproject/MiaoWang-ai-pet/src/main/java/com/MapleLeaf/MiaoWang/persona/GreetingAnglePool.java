package com.MapleLeaf.MiaoWang.persona;

import java.util.List;
import java.util.Map;
import java.util.concurrent.ThreadLocalRandom;

/**
 * 自动问候的「开口角度候选池」—— 问候语<b>多样性</b>的唯一来源。
 *
 * <h3>为什么需要它</h3>
 * 催生这个类的现象是：宠物每次主动开口都在讨吃的（「主人，我饿了」「有罐头吗」）。
 * 根因不在代码里（全仓库没有一句写死的问候语），而在提示词：原来的问候指令只说
 * "现在是{时段}，主动打个招呼"，<b>没有给开口的角度</b>，模型就顺着"猫"这个刻板印象
 * 自由发挥，落到"要吃的最省事"这条最短路径上。
 *
 * <p>解法是"每次从池子里换一个角度交给模型"，而不是写死句子：
 * 宠物的话仍由模型现生成（口吻、长短、结合上下文这些提示词管得住），
 * 我们只决定<b>这次关心主人的哪件事</b>。写死句子会立刻失去"像宠物临时说的话"那种自然感。
 *
 * <h3>怎么继续往池子里加句子（就是加一条字符串）</h3>
 * <ol>
 *   <li>找到下面 {@link #ANGLES} 里对应的时段，往那个 {@code List.of(...)} 里追加一条；</li>
 *   <li>每条写的是<b>给模型看的开口角度</b>（第三人称祈使句，如"问主人今天累不累"），
 *       <b>不是</b>要宠物说的原话 —— 原话由模型按宠物口吻生成；</li>
 *   <li>内容请落在主人身上（累不累 / 吃没吃 / 喝水 / 别熬夜 / 早点休息 / 心情），
 *       不要写"要吃的""要陪玩"这种索取型角度：那是这次要治的病；</li>
 *   <li>句子里不要出现花括号（会被提示词占位符替换吃掉）与百分号（模板里另有格式化语义）；</li>
 *   <li>加完不用改任何别的文件 —— {@link PetPersonaFactory#greetingInstruction} 会自动抽到。</li>
 * </ol>
 *
 * <h3>它能让"多样"到什么程度（说清边界，别高估）</h3>
 * 抽签发生在<b>每次真·生成</b>时，而问候受两道闸门保护（一时段只生成一次：Redis 缓存 +
 * 回查本时段已有发言，见 {@code AiPetChatService#greet}）。所以：
 * <ul>
 *   <li><b>不同时段</b>（一天最多 5 段）天然不同：池子按时段分开，早上的角度和深夜的角度不重叠；</li>
 *   <li><b>同一时段反复刷首页</b>拿到的是同一句 —— 这是刻意保留的（一天最多 5 次模型调用），
 *       不是这次改动的遗漏；</li>
 *   <li>同一个时段隔天再抽，多数情况也会换一条（每段 6 条里随机）。</li>
 * </ul>
 */
public final class GreetingAnglePool {

    /**
     * 每个时段一组"关心主人"的开口角度。
     *
     * <p>按时段分池而不是一个大池子：深夜的角度（催睡觉、别熬夜）和早上的角度（睡得怎么样、吃早饭没）
     * 本来就该不一样，混在一起随机会让"时间感"失效 —— 那正是首页问候最像"它真的在等我"的地方。
     */
    private static final Map<TimeSlot, List<String>> ANGLES = Map.of(

            TimeSlot.NIGHT, List.of(
                    "问主人怎么这么晚还没睡，用撒娇的方式催主人早点去休息",
                    "提醒主人别熬夜了，说你已经困了，想等主人一起睡",
                    "小声问主人是不是有心事才睡不着，让主人别一个人硬扛着",
                    "问主人今天累不累，劝主人放下手机去睡觉",
                    "提醒主人睡前喝一小口水，但别喝太多免得夜里老起来",
                    "说你想主人了，问主人这个点还在忙什么"),

            TimeSlot.MORNING, List.of(
                    "问主人昨晚睡得怎么样，有没有赖床",
                    "问主人吃早饭了没有，提醒主人别空着肚子出门",
                    "问主人今天忙不忙，说你已经准备好陪主人了",
                    "问主人今天有什么安排，说你会乖乖在家等他回来",
                    "说你早上最有精神，问主人睡醒有没有缓过来",
                    "问主人今天心情怎么样，说要是累了就早点回来歇着"),

            TimeSlot.NOON, List.of(
                    "问主人午饭吃了没有，让主人别忙到忘了吃饭",
                    "提醒主人吃完别马上趴着，起来走两步",
                    "问主人上午累不累，中午能不能眯一会儿",
                    "说你也要睡午觉了，问主人要不要一起歇会儿",
                    "提醒主人多喝点水，别一忙起来就忘了",
                    "说你中午打了个盹，问主人有没有空歇一会儿"),

            TimeSlot.AFTERNOON, List.of(
                    "问主人下午是不是有点困，提醒主人起来活动一下",
                    "提醒主人喝口水，别一直盯着屏幕",
                    "问主人今天手头的事顺不顺，说你可以安安静静陪着他",
                    "提醒主人少喝点咖啡，不然晚上又睡不着",
                    "问主人今天累不累，说你想蹭蹭他给他打打气",
                    "问主人有没有遇到烦心事，说讲给你听听也行"),

            TimeSlot.EVENING, List.of(
                    "问主人晚饭吃了没有，让主人别又凑合一顿",
                    "问主人今天累不累，说你想陪他坐一会儿",
                    "提醒主人今天早点休息，别再熬夜了",
                    "问主人今天有没有开心的事，讲给你听听",
                    "说你在家等了他一天，问主人今天过得怎么样",
                    "提醒主人该喝水了，晚上别喝太浓的茶"));

    /**
     * 兜底角度：时段表万一漏了一段（以后新增时段忘了配池子），也不至于把空指令给模型。
     */
    private static final String FALLBACK_ANGLE = "问主人今天过得怎么样，用你的口吻关心他一句";

    private GreetingAnglePool() {
    }

    /**
     * 随机抽一个角度（每次真·生成抽一次，抽签用 {@link ThreadLocalRandom}，无锁、不共享状态）。
     *
     * @param slot 当前时段；为 {@code null} 或该时段没配池子时返回兜底角度
     */
    public static String pick(TimeSlot slot) {
        List<String> candidates = slot == null ? null : ANGLES.get(slot);
        if (candidates == null || candidates.isEmpty()) {
            return FALLBACK_ANGLE;
        }
        return candidates.get(ThreadLocalRandom.current().nextInt(candidates.size()));
    }
}